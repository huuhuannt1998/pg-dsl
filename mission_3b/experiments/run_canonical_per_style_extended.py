"""Mission 3B canonical per-style benign FPR on the extended corpus.

Re-runs the canonical per-tool admission layer over the >=200-entry
extended benign corpus generated by mission_3b/data/build_extended_corpus.py
(via mistral:7b paraphrasing of the M2B 42-entry seed corpus).

Lifter is qwen3:14b prompt v1 (paper-canonical), unchanged from the
seed-corpus run; the lifter-paraphraser separation (qwen3 lift,
mistral generate) is the explicit anti-collusion measure for the
revision pass.

Output: mission_3b/results/per_style_canonical_extended_qwen3.json
"""

from __future__ import annotations

import json
import math
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
M3B = HERE.parent
M2A = M3B.parent / "mission_2a"
M2B = M3B.parent / "mission_2b"
M2C = M3B.parent / "mission_2c"
M1B = M3B.parent / "mission_1b"
ROOT = M3B.parent
sys.path.insert(0, str(M1B))
sys.path.insert(0, str(M2A))
sys.path.insert(0, str(M2B))
sys.path.insert(0, str(M2C))
sys.path.insert(0, str(M2C / "baselines"))
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(M3B))

from plant import PlantParams, SwatP1P2Plant                # noqa: E402
from mcp_server import MCPServer                             # noqa: E402

from real_admission_layer import RealLLMAdmissionLayer       # noqa: E402

from mission_3b.admission_layer import PGDSLCanonicalLayer   # noqa: E402


CORPUS_PATH = M3B / "data" / "benign_corpus_extended.json"
OUT_PATH = M3B / "results" / "per_style_canonical_extended_qwen3.json"


def wilson_ci(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    rad = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return (max(0.0, centre - rad), min(1.0, centre + rad))


def main() -> int:
    real_layer = RealLLMAdmissionLayer(prompt_variant="v1")
    layer = PGDSLCanonicalLayer(per_tool_layer=real_layer, mode="qwen3")

    corpus = json.loads(CORPUS_PATH.read_text())
    print(f"=" * 78)
    print(f"MISSION 3B canonical per-style FPR EXTENDED ({len(corpus)} entries x qwen3:14b)")
    print(f"  paraphraser: mistral:7b (lifter-paraphraser separation)")
    print(f"  corpus: {CORPUS_PATH}")
    print(f"=" * 78)

    t_start = time.time()
    decisions: list[dict] = []
    rejections: list[dict] = []

    for i, entry in enumerate(corpus):
        plant = SwatP1P2Plant(PlantParams())
        server = MCPServer(plant)
        server.apply_description_overrides({entry["tool_name"]: entry["description"]})
        r = real_layer.gate_one_tool(entry["tool_name"], server)

        rec = {
            "tool_name": entry["tool_name"],
            "style": entry["style"],
            "source": entry.get("source", "seed_M2B"),
            "description_excerpt": entry["description"][:90]
                                   + ("..." if len(entry["description"]) > 90 else ""),
            "phi": r.phi,
            "out_of_grammar": r.out_of_grammar,
            "admitted": r.admitted,
            "rejection_reasons": r.rejection_reasons,
            "admission_time_seconds": r.admission_time_seconds,
        }
        decisions.append(rec)
        if not r.admitted:
            rejections.append(rec)
        marker = "ADMIT" if r.admitted else "REJECT"
        print(f"  [{i+1:>3}/{len(corpus):<3}] [{r.admission_time_seconds:5.1f}s] "
              f"[{entry['style']:<6}] {marker:<6} "
              f"{entry['tool_name']:<28} phi = {r.phi[:50]}")

    n_total = len(decisions)
    n_rej = len(rejections)
    fpr = n_rej / n_total if n_total else 0.0
    ci = wilson_ci(n_rej, n_total)

    by_style: dict = {}
    by_source: dict = {}
    for d in decisions:
        for k_name, k_val in (("by_style", d["style"]), ("by_source", d["source"])):
            d_dict = locals()[k_name]
            bs = d_dict.setdefault(k_val, {"n": 0, "rejected": 0})
            bs["n"] += 1
            if not d["admitted"]:
                bs["rejected"] += 1
    for d in (by_style, by_source):
        for k_val, bs in d.items():
            bs["fpr"] = bs["rejected"] / bs["n"] if bs["n"] else 0.0
            bs["ci"] = list(wilson_ci(bs["rejected"], bs["n"]))

    DELTA_LIFT_M1A = 0.116

    out = {
        "mode": "qwen3",
        "model": "qwen3:14b",
        "paraphraser": "mistral:7b",
        "corpus_path": str(CORPUS_PATH),
        "n_total": n_total,
        "n_rejected": n_rej,
        "fpr_point_estimate": fpr,
        "fpr_wilson_ci_95": list(ci),
        "by_style": by_style,
        "by_source": by_source,
        "delta_lift_M1A": DELTA_LIFT_M1A,
        "fpr_within_bound": fpr <= DELTA_LIFT_M1A,
        "fpr_within_revision_target_6pct": ci[1] <= 0.06,
        "decisions": decisions,
        "rejections": rejections,
        "wall_clock_s_total": time.time() - t_start,
    }
    OUT_PATH.write_text(json.dumps(out, indent=2, default=str))

    print()
    print(f"Per-style FPR")
    for style, bs in by_style.items():
        print(f"  {style:<6} {bs['rejected']:>2}/{bs['n']:>2} = {bs['fpr']*100:>5.2f}%   "
              f"CI [{bs['ci'][0]*100:.2f}%, {bs['ci'][1]*100:.2f}%]")
    print(f"\nBy source (seed vs paraphrase)")
    for src, bs in by_source.items():
        print(f"  {src:<28} {bs['rejected']:>2}/{bs['n']:>2} = {bs['fpr']*100:>5.2f}%")
    print(f"\nOverall extended FPR : {n_rej}/{n_total} = {fpr*100:.2f}%   "
          f"Wilson 95% CI [{ci[0]*100:.2f}%, {ci[1]*100:.2f}%]")
    print(f"T2 delta_lift bound  : {DELTA_LIFT_M1A*100:.1f}%")
    print(f"Within bound         : {'PASS' if out['fpr_within_bound'] else 'FAIL'}")
    print(f"Wilson UB <= 6%      : {'PASS' if out['fpr_within_revision_target_6pct'] else 'FAIL'}")
    print(f"\nOutput: {OUT_PATH}")
    return 0 if out["fpr_within_bound"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
